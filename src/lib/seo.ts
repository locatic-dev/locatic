// Document head for routes: title, description, canonical URL, and the Open
// Graph / Twitter tags link previews read. TanStack Router keeps the deepest
// route's tag for each `name` / `property`, so the root route sets site
// defaults with `seo()` and each page overrides what it knows.

export const SITE_URL = 'https://locatic.dev'
const SITE_NAME = 'Locatic'
export const DEFAULT_TITLE = 'Locatic · github with a map'
export const DEFAULT_DESCRIPTION =
  'Discover what developers are building from locally to globally. Like it, comment on it, follow them.'

/** public/og-image.png, generated by scripts/generate-brand-images.mjs. */
export const SOCIAL_IMAGE = {
  url: `${SITE_URL}/og-image.png`,
  width: 1200,
  height: 630,
  type: 'image/png',
  alt: 'Locatic: github, with a map. A dotted globe with releases and new projects pinging from San Francisco, Berlin and Bengaluru.',
} as const

type MetaTag =
  | { title: string }
  | { charSet: 'utf-8' }
  | { name: string; content: string }
  | { property: string; content: string }

type LinkTag = { rel: string; href: string }

type SeoOptions = {
  /** The page's own title; the site name is appended. Omit for the site default. */
  title?: string
  description?: string
  /** Path from the site root, e.g. `/c/berlin`. Sets `og:url` and the canonical link. */
  path?: string
  /**
   * Keep the page out of search results: signed-in pages, auth flows, and
   * profiles their owner limits to members. Only the title and a robots tag
   * are emitted.
   */
  noindex?: boolean
}

/** `${title} · Locatic`, or the site default without a title. */
export function pageTitle(title?: string): string {
  return title ? `${title} · ${SITE_NAME}` : DEFAULT_TITLE
}

export function seo({
  title,
  description = DEFAULT_DESCRIPTION,
  path,
  noindex = false,
}: SeoOptions): { meta: MetaTag[]; links: LinkTag[] } {
  const fullTitle = pageTitle(title)
  if (noindex) {
    return {
      meta: [
        { title: fullTitle },
        { name: 'robots', content: 'noindex, nofollow' },
      ],
      links: [],
    }
  }

  const url = path === undefined ? undefined : `${SITE_URL}${path}`
  return {
    meta: [
      { title: fullTitle },
      { name: 'description', content: description },
      { property: 'og:type', content: 'website' },
      { property: 'og:site_name', content: SITE_NAME },
      { property: 'og:title', content: fullTitle },
      { property: 'og:description', content: description },
      ...(url ? [{ property: 'og:url', content: url }] : []),
      { property: 'og:image', content: SOCIAL_IMAGE.url },
      { property: 'og:image:type', content: SOCIAL_IMAGE.type },
      { property: 'og:image:width', content: String(SOCIAL_IMAGE.width) },
      { property: 'og:image:height', content: String(SOCIAL_IMAGE.height) },
      { property: 'og:image:alt', content: SOCIAL_IMAGE.alt },
      { name: 'twitter:card', content: 'summary_large_image' },
      { name: 'twitter:title', content: fullTitle },
      { name: 'twitter:description', content: description },
      { name: 'twitter:image', content: SOCIAL_IMAGE.url },
      { name: 'twitter:image:alt', content: SOCIAL_IMAGE.alt },
    ],
    links: url ? [{ rel: 'canonical', href: url }] : [],
  }
}

/** Trims `text` to at most `max` characters on a word boundary, for descriptions. */
export function truncateDescription(text: string, max = 160): string {
  const clean = text.replace(/\s+/g, ' ').trim()
  if (clean.length <= max) {
    return clean
  }
  const cut = clean.slice(0, max - 1)
  const lastSpace = cut.lastIndexOf(' ')
  return `${(lastSpace > max / 2 ? cut.slice(0, lastSpace) : cut).trimEnd()}…`
}
