#!/usr/bin/env node
// Land dots for the landing globe.
//
// Run: pnpm geo:land-dots   (writes src/lib/land-dots.ts)
//
// Samples an evenly spaced sphere grid and keeps the points on land, using
// Natural Earth's 1:110m land polygons from `world-atlas`. The grid has
// constant-latitude rows `LAND_GRID_STEP` degrees apart; each row holds
// round(360 * cos(lat) / step) points, so neighbouring dots sit about one
// step apart everywhere on the sphere. The output is one bit per grid point
// (1 = land), base64 encoded; `decodeLandDots` in
// src/features/landing/globe.ts walks the same grid to decode it.
//
// A point counts as land when its centre, or any of four points a third of a
// step away, is on land. That keeps thin coasts and islands (Japan, the UK,
// New Zealand, Italy) visible at this spacing.
//
// Uses devDependencies only (world-atlas, topojson-client, d3-geo); nothing
// here ships to the client.

import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)

/** Degrees between grid rows, and between points along a row at the equator. */
const LAND_GRID_STEP = 1.8
const OUTPUT = new URL('../src/lib/land-dots.ts', import.meta.url)

const topology = JSON.parse(
  readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'),
)
const land = feature(topology, topology.objects.land)

const isLand = (lng, lat) => geoContains(land, [lng, lat])
const NUDGE = LAND_GRID_STEP / 3

const rows = Math.round(180 / LAND_GRID_STEP)
const bits = []
let landCount = 0
for (let row = 0; row < rows; row++) {
  const lat = 90 - (row + 0.5) * LAND_GRID_STEP
  const count = Math.max(
    1,
    Math.round((360 * Math.cos((lat * Math.PI) / 180)) / LAND_GRID_STEP),
  )
  for (let index = 0; index < count; index++) {
    const lng = -180 + ((index + 0.5) * 360) / count
    const nudge = NUDGE / Math.max(Math.cos((lat * Math.PI) / 180), 0.2)
    const onLand =
      isLand(lng, lat) ||
      isLand(lng + nudge, lat) ||
      isLand(lng - nudge, lat) ||
      isLand(lng, Math.min(lat + NUDGE, 90)) ||
      isLand(lng, Math.max(lat - NUDGE, -90))
    bits.push(onLand ? 1 : 0)
    if (onLand) landCount++
  }
}

const bytes = Buffer.alloc(Math.ceil(bits.length / 8))
bits.forEach((bit, index) => {
  if (bit) bytes[index >> 3] |= 1 << (index & 7)
})
const encoded = bytes.toString('base64')

const LINE = 76
const lines = []
for (let start = 0; start < encoded.length; start += LINE) {
  lines.push(`  '${encoded.slice(start, start + LINE)}',`)
}

writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-land-dots.mjs (\`pnpm geo:land-dots\`). Do not edit.
// Land data: Natural Earth 1:110m land via world-atlas (public domain).

/** Degrees between grid rows, and between points along a row at the equator. */
export const LAND_GRID_STEP = ${LAND_GRID_STEP}

/** Grid points on land. */
export const LAND_DOT_COUNT = ${landCount}

/** One bit per grid point, row by row from the north pole, 1 = land. */
export const LAND_BITS = [
${lines.join('\n')}
].join('')
`,
)

console.log(
  `wrote ${landCount} land dots of ${bits.length} grid points (${encoded.length} base64 chars) to src/lib/land-dots.ts`,
)
